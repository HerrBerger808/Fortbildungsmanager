        </div>
        <div class="form-group">
          <label>Admin Name (optional)</label>
          <input type="text" name="admin_name" placeholder="Vor- und Nachname">
        </div>
        <button type="submit" name="create_admin" value="1" class="btn btn-primary">Installation abschließen</button>
      </form>
    </div>

  <?php elseif ($currentStep === 5): ?>
    <div class="card" style="text-align:center">
      <div style="font-size:3rem;margin-bottom:12px">✓</div>
      <h2>Installation abgeschlossen!</h2>
