<?php
// Installation wizard
// Access via /install – creates DB tables and first admin user.
// Blocked automatically once setup_complete = 1.

declare(strict_types=1);

// public/ is the DocumentRoot; app root is one level up
$appRoot = dirname(__DIR__);

require_once $appRoot . '/config/config.php';

$step    = (int)($_GET['step'] ?? 1);
$errors  = [];
$success = '';

// ── Helper ────────────────────────────────────────────────────────────
function tryConnect(string $host, string $port, string $db, string $user, string $pass): ?PDO {
    try {
        $pdo = new PDO(
            "mysql:host={$host};port={$port};charset=utf8mb4",
            $user, $pass,
            [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION, PDO::ATTR_EMULATE_PREPARES => false]
        );
        return $pdo;
    } catch (PDOException) {
        return null;
    }
}

// Check if already installed
$alreadyInstalled = false;
try {
    require_once $appRoot . '/config/database.php';
    $val = Database::getSetting('setup_complete', '0');
    if ($val === '1') $alreadyInstalled = true;
} catch (Throwable) {
    // DB not yet set up
}

if ($alreadyInstalled) {
    header('Location: ' . APP_URL . '/');
    exit;
}

// ── Step 2: Test DB + write local config ──────────────────────────────
if ($step === 2 && $_SERVER['REQUEST_METHOD'] === 'POST') {
    $dbHost = trim($_POST['db_host'] ?? 'localhost');
    $dbPort = trim($_POST['db_port'] ?? '3306');
    $dbName = trim($_POST['db_name'] ?? 'fortbildungsmanager');
    $dbUser = trim($_POST['db_user'] ?? '');
    $dbPass = $_POST['db_pass'] ?? '';
    $appUrl = rtrim(trim($_POST['app_url'] ?? ''), '/');
    $appSec = bin2hex(random_bytes(24));

    $pdo = tryConnect($dbHost, $dbPort, $dbName, $dbUser, $dbPass);
    if (!$pdo) {
        // Try creating the database
        $pdoRoot = tryConnect($dbHost, $dbPort, '', $dbUser, $dbPass);
        if ($pdoRoot) {
            $pdoRoot->exec("CREATE DATABASE IF NOT EXISTS `{$dbName}` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci");
            $pdo = tryConnect($dbHost, $dbPort, $dbName, $dbUser, $dbPass);
        }
    }

    if (!$pdo) {
        $errors[] = 'Datenbankverbindung fehlgeschlagen. Bitte prüfen Sie Host, Port, Benutzer und Passwort.';
    } else {
        // Write local config
        $localConfig = <<<PHP
<?php
// Local configuration – generated by installer
define('DB_HOST', '{$dbHost}');
define('DB_PORT', '{$dbPort}');
define('DB_NAME', '{$dbName}');
define('DB_USER', '{$dbUser}');
define('DB_PASS', '{$dbPass}');
define('APP_URL', '{$appUrl}');
define('APP_SECRET', '{$appSec}');
PHP;
        $localFile = $appRoot . '/config/local.php';
        if (file_put_contents($localFile, $localConfig) === false) {
            $errors[] = 'config/local.php konnte nicht geschrieben werden. Bitte prüfen Sie die Schreibrechte: chmod 775 /var/www/fobi/config';
        } else {
            chmod($localFile, 0640); // owner rw, group r, others nothing
            header('Location: ' . $appUrl . '/install?step=3');
            exit;
        }
    }
}

// ── Step 3: Import schema ─────────────────────────────────────────────
if ($step === 3) {
    try {
        require_once $appRoot . '/config/database.php';
        $sql = file_get_contents($appRoot . '/sql/schema.sql');
        // Split by semicolon, execute each statement
        $statements = array_filter(array_map('trim', explode(';', $sql)));
        $pdo        = Database::getInstance();
        foreach ($statements as $stmt) {
            if ($stmt) $pdo->exec($stmt);
        }
        $success = 'Datenbank-Schema erfolgreich importiert.';
        $step    = 4;
    } catch (Throwable $e) {
        $errors[] = 'Fehler beim Importieren: ' . $e->getMessage();
    }
}

// ── Step 4: Create admin user ──────────────────────────────────────────
if ($step === 4 && $_SERVER['REQUEST_METHOD'] === 'POST' && isset($_POST['create_admin'])) {
    require_once $appRoot . '/config/database.php';
    $adminEmail  = strtolower(trim($_POST['admin_email'] ?? ''));
    $adminName   = trim($_POST['admin_name'] ?? '');
    $domain      = substr($adminEmail, strrpos($adminEmail, '@') + 1);
    $appName     = trim($_POST['app_name'] ?? 'Fortbildungsmanager');

    if (!filter_var($adminEmail, FILTER_VALIDATE_EMAIL)) {
        $errors[] = 'Bitte geben Sie eine gültige E-Mail-Adresse ein.';
    } else {
        // Save app settings
        Database::setSetting('app_name',     $appName);
        Database::setSetting('app_url',      APP_URL);
        Database::setSetting('admin_email',  $adminEmail);
        Database::setSetting('mail_from',    $adminEmail);
        Database::setSetting('mail_from_name', $appName);

        // Add domain as auto-approved
        Database::execute(
            'INSERT INTO `allowed_domains` (`domain`, `auto_approved`) VALUES (?, 1)
             ON DUPLICATE KEY UPDATE `auto_approved` = 1',
            [$domain]
        );

        // Create or update admin user
        $existing = Database::fetchOne('SELECT id FROM `users` WHERE `email` = ?', [$adminEmail]);
        if ($existing) {
            Database::execute(
                'UPDATE `users` SET `name` = ?, `role` = "admin", `status` = "active" WHERE `id` = ?',
                [$adminName, $existing['id']]
            );
        } else {
            Database::execute(
                'INSERT INTO `users` (`email`, `name`, `role`, `status`) VALUES (?, ?, "admin", "active")',
                [$adminEmail, $adminName]
            );
        }

        Database::setSetting('setup_complete', '1');
        $step = 5; // Done
    }
}

// ── HTML output ────────────────────────────────────────────────────────
$currentStep = $step;
?>
