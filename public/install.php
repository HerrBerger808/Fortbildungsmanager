  <div class="steps">
    <div class="step-dot <?= $currentStep >= 1 ? ($currentStep > 1 ? 'done' : 'active') : '' ?>">Start</div>
    <div class="step-dot <?= $currentStep >= 2 ? ($currentStep > 2 ? 'done' : 'active') : '' ?>">Datenbank</div>
    <div class="step-dot <?= $currentStep >= 3 ? ($currentStep > 3 ? 'done' : 'active') : '' ?>">Schema</div>
    <div class="step-dot <?= $currentStep >= 4 ? ($currentStep > 4 ? 'done' : 'active') : '' ?>">Admin</div>
    <div class="step-dot <?= $currentStep >= 5 ? 'done' : '' ?>">Fertig</div>
  </div>

  <?php foreach ($errors as $e): ?>
    <div class="alert alert-error"><?= htmlspecialchars($e) ?></div>
  <?php endforeach; ?>
  <?php if ($success): ?>
    <div class="alert alert-success"><?= htmlspecialchars($success) ?></div>
  <?php endif; ?>

  <?php if ($currentStep === 1): ?>
    <div class="card">
      <h2>Willkommen</h2>
      <p>Dieser Assistent richtet den Fortbildungsmanager ein. Sie benötigen:</p>
      <ul>
        <li>PHP 8.1+ mit PDO-MySQL-Erweiterung</li>
        <li>MariaDB / MySQL Datenbankzugang</li>
        <li>Apache2 mit <code>mod_rewrite</code></li>
      </ul>
      <p>Bitte stellen Sie sicher, dass das Verzeichnis <code>config/</code> (eine Ebene über <code>public/</code>) für den Webserver schreibbar ist,
         damit <code>config/local.php</code> angelegt werden kann.</p>
      <a href="?step=2" class="btn btn-primary">Weiter</a>
    </div>

  <?php elseif ($currentStep === 2): ?>
    <div class="card">
      <h2>Datenbankverbindung</h2>
      <form method="post" action="?step=2" class="form">
        <div class="form-row">
          <div class="form-group">
            <label>Host</label>
            <input type="text" name="db_host" value="<?= htmlspecialchars($_POST['db_host'] ?? 'localhost') ?>" required>
          </div>
          <div class="form-group">
            <label>Port</label>
            <input type="number" name="db_port" value="<?= htmlspecialchars($_POST['db_port'] ?? '3306') ?>" required>
          </div>
        </div>
        <div class="form-group">
          <label>Datenbankname</label>
          <input type="text" name="db_name" value="<?= htmlspecialchars($_POST['db_name'] ?? 'fortbildungsmanager') ?>" required>
          <small>Wird angelegt, falls noch nicht vorhanden.</small>
        </div>
        <div class="form-row">
          <div class="form-group">
            <label>Datenbankbenutzer</label>
            <input type="text" name="db_user" value="<?= htmlspecialchars($_POST['db_user'] ?? '') ?>" required>
          </div>
